    private void carregarComboBoxes() {
        // 1. Limpa todas as ComboBoxes antes de carregar
        jUsuarios.removeAllItems();
        jAparelho.removeAllItems();
        jChip.removeAllItems();
        
        // 2. Adiciona os itens iniciais/padrão
        jUsuarios.addItem("Selecione um Colaborador...");
        jAparelho.addItem("Selecione um Aparelho...");
        jChip.addItem("Selecione um Chip...");

        try {
            // --- CARREGAR APARELHOS ---
            AparelhoController apaControl = new AparelhoController();
            List<Aparelho> aparelhos = apaControl.listar(this.sessaoLogada);
            if (aparelhos != null && !aparelhos.isEmpty()) {
                for (Aparelho a : aparelhos) {
                    jAparelho.addItem(a.getIdApa() + " - IMEI: " + a.getImeiApa());
                }
            }

            // --- CARREGAR CHIPS ---
            ChipController chipControl = new ChipController();
            List<Chip> chips = chipControl.listar(this.sessaoLogada);
            if (chips != null && !chips.isEmpty()) {
                for (Chip c : chips) {
                    jChip.addItem(c.getIdChip() + " - Tel: " + c.getNumeroChip());
                }
            }

            // --- CARREGAR USUÁRIOS (COLABORADORES) ---
            UsuarioController usuControl = new UsuarioController();
            Sessao sessao = null;
            List<Usuario> usuarios = usuControl.listar(sessao);
            if (usuarios != null && !usuarios.isEmpty()) {
                for (Usuario u : usuarios) {
                    // Adiciona no formato "ID - Nome" para extrair o ID com split(" - ")[0]
                    jUsuarios.addItem(u.getIdUsu() + " - " + u.getNomeUsu());
                }
            }

        } catch (Exception e) {
            System.out.println("Erro ao carregar ComboBoxes: " + e.getMessage());
        }
    }
    private void carregarTabela() {
        javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) tbEmprestimo.getModel();
        model.setRowCount(0); 

        try {
            EmprestimoController controleEmp = new EmprestimoController();
           UsuarioController controleUsu = new UsuarioController();
            
            java.util.List<Emprestimo> lista = controleEmp.listar(this.sessaoLogada);

            if (lista != null) {
                for (Emprestimo e : lista) {
                    // Pede ao Controller para traduzir o ID no nome real
                    String nomeColaborador = controleUsu.buscarNomePorId(e.getIdUsu());
                    
                    model.addRow(new Object[]{
                        e.getIdEmp(),           // 1ª Coluna: ID
                        nomeColaborador,        // 2ª Coluna: Nome do Colaborador
                        e.getIdApa(),           // 3ª Coluna: Aparelho
                        e.getIdChip(),          // 4ª Coluna: Chip
                        e.getStatusEmp()        // 5ª Coluna: Estado
                    });
                }
            }
        } catch (Exception e) {
            System.out.println("Erro ao carregar tabela de empréstimos: " + e.getMessage());
        }
    }
