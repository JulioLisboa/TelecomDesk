    private void jRegistarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jRegistarActionPerformed
        // TODO add your handling code here:
        try {
            String txtApa = jAparelho.getSelectedItem().toString();
            String txtChip = jChip.getSelectedItem().toString();
            String txtUsu = jUsuarios.getSelectedItem().toString();

            // Proteção para não salvar caso o usuário não tenha selecionado nada
            if (txtApa.startsWith("Selecione") || txtChip.startsWith("Selecione") || txtUsu.startsWith("Selecione")) {
                JOptionPane.showMessageDialog(this, "Selecione opções válidas para Colaborador, Aparelho e Chip!");
                return;
            }

            // O split(" - ")[0] extrai apenas o UUID (a parte antes do traço)
            String idUsu = txtUsu.split(" - ")[0];
            String idApa = txtApa.split(" - ")[0];
            String idChip = txtChip.split(" - ")[0];
            
            br.com.controle.EmprestimoController controle = new br.com.controle.EmprestimoController();
            
            if (controle.regitsrarEmprestimo(this.sessaoLogada, idApa, idChip, idUsu)) {
                JOptionPane.showMessageDialog(this, "Empréstimo registrado com sucesso!");
                carregarTabela(); // Atualiza a tabela imediatamente
                jLimparActionPerformed(evt);
            } else {
                JOptionPane.showMessageDialog(this, "Erro ao registrar empréstimo. Verifique as permissões.");
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Erro: " + e.getMessage());
        }
    }//GEN-LAST:event_jRegistarActionPerformed

