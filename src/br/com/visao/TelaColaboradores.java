    private void jCadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jCadastrarActionPerformed
        // TODO add your handling code here:                                      
        try {
            
            String nome = jNome.getText();
            String email = jEmail.getText();
            String telefone = jTel.getText();
            String senha = new String(jSenha.getPassword());

            if (jPerfil.getSelectedItem() == null
                    || "Selecione um Perfil...".equals(jPerfil.getSelectedItem().toString())) {
                JOptionPane.showMessageDialog(this, "Selecione um perfil!");
                return;
            }
            if (jSetor.getSelectedItem() == null
                    || "Selecione um Setor...".equals(jSetor.getSelectedItem().toString())) {
                JOptionPane.showMessageDialog(this, "Por favor, selecione um setor!");
                return;
            }

            String perfilSelecionado = jPerfil.getSelectedItem().toString().trim().toUpperCase();
            String setorSelecionado = jSetor.getSelectedItem().toString();
            String idSetor = setorSelecionado.split(" - ", 2)[0].trim();
            UsuarioController controle = new UsuarioController();

            if (controle.cadastrar(nome, email, telefone, senha, perfilSelecionado, idSetor)) {
                JOptionPane.showMessageDialog(this, "Cadastro realizado como " + perfilSelecionado + "!");
                carregarTabela();
                jLimparCamposActionPerformed(evt);
            } else {
                JOptionPane.showMessageDialog(this, "Erro ao cadastrar. Verifique os dados e o perfil selecionado.");
            }
            
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Erro: " + e.getMessage());
        }
    
    }//GEN-LAST:event_jCadastrarActionPerformed

