    private void jEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jEditarActionPerformed
        int linhaSelecionada = tbColaboradores.getSelectedRow();
        if (linhaSelecionada == -1) {
            JOptionPane.showMessageDialog(this, "Selecione um colaborador na tabela!");
            return;
        }

        int linhaModelo = tbColaboradores.convertRowIndexToModel(linhaSelecionada);
        String status = String.valueOf(tbColaboradores.getModel().getValueAt(linhaModelo, 5));
        if ("INATIVO".equalsIgnoreCase(status)) {
            JOptionPane.showMessageDialog(this, "Não é possível editar um colaborador inativo.");
            return;
        }

        if (jSetor.getSelectedItem() == null
                || "Selecione um Setor...".equals(jSetor.getSelectedItem().toString())) {
            JOptionPane.showMessageDialog(this, "Selecione um setor!");
            return;
        }
        if (jPerfil.getSelectedItem() == null
                || "Selecione um Perfil...".equals(jPerfil.getSelectedItem().toString())) {
            JOptionPane.showMessageDialog(this, "Selecione um perfil!");
            return;
        }

        String setorSelecionado = jSetor.getSelectedItem().toString();
        String idSetor = setorSelecionado.split(" - ", 2)[0].trim();

        Usuario usu = new Usuario();
        usu.setIdUsu(String.valueOf(tbColaboradores.getModel().getValueAt(linhaModelo, 0)));
        usu.setNomeUsu(jNome.getText().trim());
        usu.setEmailUsu(jEmail.getText().trim());
        usu.setTelefoneUsu(jTel.getText().trim());
        usu.setPerfilUsu(jPerfil.getSelectedItem().toString());
        usu.setIdSet(idSetor);

        UsuarioController controle = new UsuarioController();
        if (controle.editar(this.sessaoLogada, usu)) {
            JOptionPane.showMessageDialog(this, "Colaborador editado com sucesso!");
            carregarTabela();
            jLimparCamposActionPerformed(evt);
        } else {
            JOptionPane.showMessageDialog(this,
                "Não foi possível editar o colaborador. Verifique os campos, suas permissões e se o cadastro está ativo.",
                "Falha na edição", JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_jEditarActionPerformed

    private void jDesativarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jDesativarActionPerformed
        // TODO add your handling code here:
        int linhaSelecionada = tbColaboradores.getSelectedRow();
        if (linhaSelecionada == -1) {
            JOptionPane.showMessageDialog(this, "Selecione um colaborador na tabela!");
            return;
        }

        String statusSelecionado = String.valueOf(tbColaboradores.getValueAt(linhaSelecionada, 5));
        if ("INATIVO".equalsIgnoreCase(statusSelecionado)) {
            JOptionPane.showMessageDialog(this, "Este colaborador já está inativo.");
            return;
        }

        String idUsu = tbColaboradores.getValueAt(linhaSelecionada, 0).toString();
        int confirm = JOptionPane.showConfirmDialog(this, "Deseja realmente desativar?", "Aviso", JOptionPane.YES_NO_OPTION);
        
        if (confirm == JOptionPane.YES_OPTION) {
            UsuarioController controle = new UsuarioController();
            if (controle.desativar(this.sessaoLogada, idUsu)) {
                JOptionPane.showMessageDialog(this, "Desativado com sucesso!");
                carregarTabela();
                jLimparCamposActionPerformed(evt);
            } else {
                JOptionPane.showMessageDialog(this, "Erro ao desativar.");
            }
        }
    }//GEN-LAST:event_jDesativarActionPerformed

