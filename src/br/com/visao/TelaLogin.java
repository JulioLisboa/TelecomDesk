    private void jEntrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jEntrarActionPerformed
        // TODO add your handling code here:                                   
        try {
            SessaoController sessaoControl = new br.com.controle.SessaoController();
            String email = jEmail.getText();
            String senha = new String(jSenha.getPassword());
            
            Sessao sessao = sessaoControl.login(email, senha);
           
            if (sessao != null) {
                TelaDashboard dashboard = new TelaDashboard(sessao);
                dashboard.setVisible(true);
                this.dispose();
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "E-mail ou senha incorretos!", "Erro", javax.swing.JOptionPane.ERROR_MESSAGE);
            }
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Erro no sistema: " + e.getMessage(), "Erro", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
        
    }//GEN-LAST:event_jEntrarActionPerformed

